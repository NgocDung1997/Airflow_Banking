"""
Generate the DAG + task files of Airflow_Banking from configuration (plain Python, no Airflow needed).

Inputs
    Bronze tables  LakeHouse_Banking/jobs/auto/bronze_tables.csv     (the SAME list the LakeHouse bronze jobs are
                                                                      generated from: one source of truth)
    Bronze DAGs    dags/auto/config/bronze_domains.csv               schedule per domain
    Silver tables  dags/auto/config/silver_tables.csv                namespace, table, date mode, schedule,
                                                                      source tables (flags to wait for, "|"-separated)
    Templates      dags/auto/templates/*.py.tpl                      (string.Template, $placeholders)

Outputs (every file starts with the GENERATED marker — never edit them by hand, re-run this script)
    dags/bronze/<domain>/bronze__<table>_task.py   one task per bronze table (runs the job, writes its flags)
    dags/bronze/<domain>/bronze__<domain>_dag.py   one DAG per domain: all its tables in a row, a failure does not
                                                   stop the next table
    dags/silver/<ns>/silver__<table>_task.py       one task per silver table (runs the job, writes its flags)
    dags/silver/<ns>/silver__<table>_dag.py        one DAG per silver table: check_source_flags → load
Generated files that are no longer produced (table removed / made inactive) are deleted.

Run (from the Airflow_Banking folder, PowerShell or Git Bash):
    python dags/auto/generate_dags.py
    python dags/auto/generate_dags.py --check        # validate + show what would change, write nothing
Then wait ~30 s: the dag-processor picks the files up; `airflow dags list-import-errors` must be empty.
"""
import argparse
import csv
import re
import sys
from pathlib import Path
from string import Template
from typing import Dict, List, Optional

AUTO_DIR = Path(__file__).resolve().parent
DAGS_DIR = AUTO_DIR.parent
REPO_DIR = DAGS_DIR.parent
DEFAULT_LAKEHOUSE = REPO_DIR.parent / "LakeHouse_Banking"
CONFIG_DIR = AUTO_DIR / "config"
TEMPLATE_DIR = AUTO_DIR / "templates"
OUTPUT_LAYERS = ("bronze", "silver")

MARKER = "# GENERATED by dags/auto/generate_dags.py"
DATE_MODES = {"cob_dt_only": "COB_DT_ONLY", "date_range": "DATE_RANGE", "no_date": "NO_DATE"}
LOAD_TYPE_MODE = {"snapshot": "COB_DT_ONLY", "incremental": "DATE_RANGE"}
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
CRON_RE = re.compile(r"^(\S+\s+){4}\S+$")


class ConfigError(Exception):
    pass


# ── Reading the configuration ───────────────────────────────────────────────────────────────────────────────
def read_csv(path: Path, required: List[str]) -> List[Dict[str, str]]:
    if not path.is_file():
        raise ConfigError(f"missing config file: {path}")
    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        missing = [c for c in required if c not in (reader.fieldnames or [])]
        if missing:
            raise ConfigError(f"{path.name}: missing column(s) {missing}")
        return [{k: (v or "").strip() for k, v in row.items()} for row in reader]


def is_active(row: Dict[str, str], where: str) -> bool:
    if row["active"] not in ("0", "1"):
        raise ConfigError(f"{where}: active must be 0 or 1, got {row['active']!r}")
    return row["active"] == "1"


def check_name(value: str, what: str, where: str) -> str:
    if not NAME_RE.match(value):
        raise ConfigError(f"{where}: {what} {value!r} must be lower_snake_case")
    return value


def schedule_literal(value: str, where: str) -> str:
    """Python literal for DAG(schedule=...): None (manual only) or a 5-field cron string."""
    if not value:
        return "None"
    if not CRON_RE.match(value):
        raise ConfigError(f"{where}: schedule {value!r} is not a 5-field cron expression")
    return repr(value)


def check_job(lakehouse: Path, job_rel: str, where: str) -> None:
    if not (lakehouse / "jobs" / job_rel).is_file():
        raise ConfigError(f"{where}: LakeHouse job not found: {lakehouse / 'jobs' / job_rel}")


def load_bronze(lakehouse: Path, tables_csv: Path) -> Dict[str, Dict[str, object]]:
    """{domain: {"schedule": ..., "tables": [...]}} for every active domain with active tables."""
    tables = read_csv(tables_csv, ["source_domain", "source_table", "target_domain", "target_table", "load_type",
                                   "active"])
    domains = read_csv(CONFIG_DIR / "bronze_domains.csv", ["domain", "schedule", "active"])
    schedules = {}
    for i, row in enumerate(domains, start=2):
        where = f"bronze_domains.csv line {i}"
        domain = check_name(row["domain"], "domain", where)
        if domain in schedules:
            raise ConfigError(f"{where}: domain {domain} listed twice")
        schedules[domain] = (is_active(row, where), schedule_literal(row["schedule"], where))

    result: Dict[str, Dict[str, object]] = {}
    seen = set()
    for i, row in enumerate(tables, start=2):
        where = f"{tables_csv.name} line {i}"
        if not is_active(row, where):
            continue
        domain = check_name(row["target_domain"], "target_domain", where)
        table = check_name(row["target_table"], "target_table", where)
        if row["load_type"] not in LOAD_TYPE_MODE:
            raise ConfigError(f"{where}: load_type must be snapshot or incremental, got {row['load_type']!r}")
        if table in seen:
            raise ConfigError(f"{where}: bronze table {table} listed twice (task / DAG names must be unique)")
        seen.add(table)
        if domain not in schedules:
            raise ConfigError(f"{where}: domain {domain} is not in auto/config/bronze_domains.csv — add it there")
        domain_active, schedule = schedules[domain]
        if not domain_active:
            continue
        job_rel = f"bronze/{domain}/bronze__{table}.py"
        check_job(lakehouse, job_rel, where)
        entry = result.setdefault(domain, {"schedule": schedule, "tables": []})
        entry["tables"].append({
            "table": table, "job_rel": job_rel, "date_mode": LOAD_TYPE_MODE[row["load_type"]],
            "description": f"Bronze {row['load_type']}: postgres {row['source_domain']}.{row['source_table']}"
                           f" → Iceberg bronze.{domain}.{table}",
        })
    return result


def load_silver(lakehouse: Path, bronze_tables: List[str]) -> List[Dict[str, object]]:
    rows = read_csv(CONFIG_DIR / "silver_tables.csv",
                    ["namespace", "table", "date_mode", "schedule", "source_tables", "active"])
    known = set(bronze_tables)
    result, seen = [], set()
    for i, row in enumerate(rows, start=2):
        where = f"silver_tables.csv line {i}"
        if not is_active(row, where):
            continue
        namespace = check_name(row["namespace"], "namespace", where)
        table = check_name(row["table"], "table", where)
        if table in seen:
            raise ConfigError(f"{where}: silver table {table} listed twice")
        seen.add(table)
        if row["date_mode"] not in DATE_MODES:
            raise ConfigError(f"{where}: date_mode must be one of {sorted(DATE_MODES)}, got {row['date_mode']!r}")
        sources = [s.strip() for s in row["source_tables"].split("|") if s.strip()]
        for source in sources:
            parts = source.split(".")
            if len(parts) != 3 or parts[0] not in ("bronze", "silver"):
                raise ConfigError(f"{where}: source {source!r} must be '<bronze|silver>.<schema>.<table>'")
            if parts[0] == "bronze" and source not in known:
                raise ConfigError(f"{where}: source {source} is not an active bronze table")
        if sources and row["date_mode"] == "no_date":
            raise ConfigError(f"{where}: a no_date table cannot wait for dated source flags")
        job_rel = f"silver/{namespace}/silver__{table}.py"
        check_job(lakehouse, job_rel, where)
        result.append({
            "namespace": namespace, "table": table, "job_rel": job_rel, "date_mode": DATE_MODES[row["date_mode"]],
            "schedule": schedule_literal(row["schedule"], where), "sources": sources,
            "description": f"Silver: {', '.join(sources) if sources else '(no source table)'}"
                           f" → silver.{namespace}.{table}",
        })
    return result


# ── Rendering ───────────────────────────────────────────────────────────────────────────────────────────────
def render(template: str, **values: object) -> str:
    text = Template((TEMPLATE_DIR / template).read_text(encoding="utf-8")).substitute(**values)
    return text.rstrip() + "\n"


def header(config_source: str) -> str:
    return f"{MARKER} from {config_source} — do not edit by hand;\n# change the config / template and re-run it."


def task_file(dag_id: str, func: str, job_rel: str, date_mode: str, flag_table: str, description: str,
              config_source: str, sources: Optional[List[str]] = None) -> str:
    sources_doc = sources_const = ""
    if sources is not None:
        sources_doc = (f"\nSource tables (flags checked before the job runs): {', '.join(sources)}"
                       if sources else "\nNo source table: nothing to check before the job runs.")
        sources_const = "\nSOURCE_TABLES = [" + ", ".join(f'"{s}"' for s in sources) + "]"
    return render("job_task.py.tpl", header=header(config_source), dag_id=dag_id, func=func, job_rel=job_rel,
                  job_file=job_rel.rsplit("/", 1)[-1], description=description, flag_table=flag_table,
                  date_mode=date_mode, sources_doc=sources_doc, sources_const=sources_const)


def build_files(lakehouse: Path, tables_csv: Path) -> Dict[Path, str]:
    files: Dict[Path, str] = {}
    bronze = load_bronze(lakehouse, tables_csv)
    bronze_source = f"LakeHouse_Banking/jobs/auto/{tables_csv.name} + auto/config/bronze_domains.csv"
    bronze_tables = []
    for domain, entry in bronze.items():
        folder = DAGS_DIR / "bronze" / domain
        dag_id = f"bronze__{domain}"
        imports, calls = [], []
        for n, t in enumerate(entry["tables"]):
            func = f"ingest_{t['table']}"
            name = f"bronze__{t['table']}"
            flag_table = f"bronze.{domain}.{t['table']}"
            bronze_tables.append(flag_table)
            files[folder / f"{name}_task.py"] = task_file(dag_id, func, t["job_rel"], t["date_mode"], flag_table,
                                                          t["description"], bronze_source)
            imports.append(f"from bronze.{domain}.{name}_task import {func}")
            calls.append(f"        {func}()," if n == 0 else f'        {func}(trigger_rule="all_done"),')
        files[folder / f"{dag_id}_dag.py"] = render(
            "bronze_domain_dag.py.tpl", header=header(bronze_source), dag_id=dag_id, domain=domain,
            schedule=entry["schedule"], table_count=len(entry["tables"]), imports="\n".join(imports),
            task_calls="\n".join(calls),
            order_text=" → ".join(f"ingest_{t['table']}" for t in entry["tables"]))

    silver_source = "auto/config/silver_tables.csv"
    for t in load_silver(lakehouse, bronze_tables):
        folder = DAGS_DIR / "silver" / t["namespace"]
        dag_id = f"silver__{t['table']}"
        func = f"load_{t['table']}"
        flag_table = f"silver.{t['namespace']}.{t['table']}"
        files[folder / f"{dag_id}_task.py"] = task_file(dag_id, func, t["job_rel"], t["date_mode"], flag_table,
                                                        t["description"], silver_source, sources=t["sources"])
        if t["sources"]:
            body = f"check_flags_task(SOURCE_TABLES, DATE_MODE) >> {func}()"
            task_imports = f"DATE_MODE, SOURCE_TABLES, {func}"
            spark_job_imports = "check_flags_task, date_params, flag_check_params"
            params = "{**date_params(DATE_MODE), **flag_check_params()}"
            flow_text = f"check_source_flags → {func}"
            flow_doc = (f"check_source_flags waits until {', '.join(t['sources'])} has a SUCCESS flag for every date "
                        f"of the run;\n{func} then runs the job and writes the flags of {flag_table}.")
        else:
            body = f"{func}()"
            task_imports = f"DATE_MODE, {func}"
            spark_job_imports = "date_params"
            params = "date_params(DATE_MODE)"
            flow_text = func
            flow_doc = f"No source table to wait for; {func} runs the job and writes the flags of {flag_table}."
        files[folder / f"{dag_id}_dag.py"] = render(
            "silver_table_dag.py.tpl", header=header(silver_source), dag_id=dag_id, flag_table=flag_table,
            description=t["description"], job_rel=t["job_rel"], flow_text=flow_text, flow_doc=flow_doc,
            task_module=f"silver.{t['namespace']}.{dag_id}_task", task_imports=task_imports,
            spark_job_imports=spark_job_imports, schedule=t["schedule"], params=params,
            namespace=t["namespace"], body=body)
    return files


def generated_files_on_disk() -> List[Path]:
    found = []
    for layer in OUTPUT_LAYERS:
        for path in (DAGS_DIR / layer).rglob("*.py"):
            with path.open(encoding="utf-8") as handle:
                if handle.readline().startswith(MARKER):
                    found.append(path)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Airflow_Banking DAG + task files from configuration")
    parser.add_argument("--lakehouse-root", type=Path, default=DEFAULT_LAKEHOUSE,
                        help=f"LakeHouse_Banking folder (default: {DEFAULT_LAKEHOUSE})")
    parser.add_argument("--bronze-tables", type=Path, default=None,
                        help="bronze table list (default: <lakehouse-root>/jobs/auto/bronze_tables.csv)")
    parser.add_argument("--check", action="store_true", help="validate and show changes, write nothing")
    args = parser.parse_args()
    tables_csv = args.bronze_tables or args.lakehouse_root / "jobs" / "auto" / "bronze_tables.csv"

    try:
        files = build_files(args.lakehouse_root, tables_csv)
    except ConfigError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    created = changed = unchanged = 0
    for path, content in sorted(files.items()):
        rel = path.relative_to(REPO_DIR).as_posix()
        if path.is_file():
            old = path.read_text(encoding="utf-8")
            if not old.startswith(MARKER):
                print(f"ERROR: {rel} exists and was not generated — move or delete it first", file=sys.stderr)
                return 2
            if old == content:
                unchanged += 1
                continue
            changed += 1
            print(f"update  {rel}")
        else:
            created += 1
            print(f"create  {rel}")
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    removed = 0
    for path in generated_files_on_disk():
        if path not in files:
            removed += 1
            print(f"delete  {path.relative_to(REPO_DIR).as_posix()}  (no longer in the config)")
            if not args.check:
                path.unlink()
    if not args.check:
        for layer in OUTPUT_LAYERS:
            for folder in sorted((DAGS_DIR / layer).rglob("*"), reverse=True):
                if folder.is_dir() and not any(p for p in folder.iterdir() if p.name != "__pycache__"):
                    for cache in folder.glob("__pycache__"):
                        for f in cache.iterdir():
                            f.unlink()
                        cache.rmdir()
                    folder.rmdir()

    mode = "CHECK (nothing written)" if args.check else "done"
    print(f"{mode}: {created} created, {changed} updated, {unchanged} unchanged, {removed} deleted "
          f"— {len(files)} generated files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
